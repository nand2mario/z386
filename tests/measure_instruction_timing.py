def parse_bit_value(raw: str) -> int | None:
    raw = raw.strip().lower()
    if not raw:
        return None
    if any(ch in raw for ch in "xzuwlh-"):
        return None
    return int(raw, 2)


def parse_vcd_header(vcd_path: Path) -> tuple[dict[str, str], dict[str, str]]:
    id_to_name: dict[str, str] = {}
    name_to_id: dict[str, str] = {}
    scope_stack: list[str] = []

    with vcd_path.open(errors="replace") as f:
        for raw_line in f:
            line = raw_line.strip()
            if line.startswith("$scope "):
                parts = line.split()
                if len(parts) >= 3:
                    scope_stack.append(parts[2])
                continue
            if line.startswith("$upscope"):
                if scope_stack:
                    scope_stack.pop()
                continue
            if line.startswith("$var "):
                parts = line.split()
                if len(parts) >= 5:
                    sig_id = parts[3]
                    name = parts[4]
                    full_name = ".".join(scope_stack + [name])
                    id_to_name[sig_id] = full_name
                    name_to_id[full_name] = sig_id
                continue
            if line.startswith("$enddefinitions"):
                break

    return id_to_name, name_to_id


def apply_changes(
    time_value: int,
    changes: dict[str, str],
    state: dict[str, str],
    ids: dict[str, str],
    clk_rises: list[int],
    i_first_events: list[tuple[int, int]],
) -> None:
    if not changes:
        return

    prev_values = {sig_id: state.get(sig_id) for sig_id in changes}
    state.update(changes)

    clk_id = ids["clk"]
    if clk_id in changes and prev_values.get(clk_id) == "0" and state.get(clk_id) == "1":
        clk_rises.append(time_value)

    eip_id = ids["eip"]
    i_first_id = ids["i_first"]
    eip_value = parse_bit_value(state.get(eip_id, ""))
    # One event per instruction start. Normally that is an i_first rising
    # edge, but z386x FAST->FAST chains keep i_first high across consecutive
    # instructions — there, each instruction start shows as an EIP change
    # while i_first stays 1 (EIP advances at every chained i_pop).
    i_first_rise = (
        i_first_id in changes
        and prev_values.get(i_first_id) == "0"
        and state.get(i_first_id) == "1"
    )
    chained_start = (
        eip_id in changes
        and state.get(i_first_id) == "1"
        and i_first_id not in changes
    )
    if (i_first_rise or chained_start) and eip_value is not None:
        i_first_events.append((time_value, eip_value))


def parse_trace(vcd_path: Path) -> tuple[list[int], list[tuple[int, int]]]:
    _id_to_name, name_to_id = parse_vcd_header(vcd_path)

    missing = [name for name in SIGNALS.values() if name not in name_to_id]
    if missing:
        raise SystemExit(f"Missing signals in {vcd_path}: {missing}")

    ids = {key: name_to_id[name] for key, name in SIGNALS.items()}
    selected_ids = set(ids.values())

    clk_rises: list[int] = []
    i_first_events: list[tuple[int, int]] = []

    state: dict[str, str] = {}
    current_time = 0
    changes: dict[str, str] = {}
    in_header = True

    with vcd_path.open(errors="replace") as f:
        for raw_line in f:
            line = raw_line.strip()
            if not line:
                continue

            if in_header:
                if line.startswith("$enddefinitions"):
                    in_header = False
                continue

            if line[0] == "#":
                apply_changes(current_time, changes, state, ids, clk_rises, i_first_events)
                changes = {}
                current_time = int(line[1:])
                continue

            if line[0] == "$":
                continue

            if line[0] in "01xXzZ":
                sig_id = line[1:]
                if sig_id in selected_ids:
                    changes[sig_id] = line[0].lower()
                continue

            if line[0] == "b":
                parts = line.split()
                if len(parts) == 2 and parts[1] in selected_ids:
                    changes[parts[1]] = parts[0][1:].lower()
                continue

    apply_changes(current_time, changes, state, ids, clk_rises, i_first_events)
    return clk_rises, i_first_events


def infer_cycle_period(clk_rises: list[int]) -> float:
    if len(clk_rises) < 3:
        raise SystemExit("Not enough clock edges to infer cycle period")
    deltas = [b - a for a, b in zip(clk_rises, clk_rises[1:])]
    return statistics.median(deltas[: min(16, len(deltas))])


def cycles(delta_time: int, cycle_period: float) -> float:
    return delta_time / cycle_period


def summarize(values: list[float]) -> str:
    if not values:
        return "n/a"
    avg = statistics.mean(values)
    lo = min(values)
    hi = max(values)
    return f"avg {avg:.1f}, min {lo:.1f}, max {hi:.1f}"


def fmt_cycles(value: float | None) -> str:
    if value is None:
        return "-"
    if abs(value - round(value)) < 0.005:
        return f"{round(value):.0f}"
    if abs(value * 10 - round(value * 10)) < 0.005:
        return f"{value:.1f}"
    return f"{value:.2f}"


def format_table_row(columns: list[str], widths: list[int]) -> str:
    cells = []
    for index, (column, width) in enumerate(zip(columns, widths)):
        if index == 0:
            cells.append(column.ljust(width))
        else:
            cells.append(column.rjust(width))
    return "| " + " | ".join(cells) + " |"


def print_comparison_table(results: list[PhaseResult], color_enabled: bool) -> None:
    headers = ["Instruction class", "80386 target", "80486 target", "z386 0.4", "z386 current"]
    rows: list[list[str]] = []

    for result in results:
        current = min(result.samples) if result.samples else None
        baseline = Z386_04_MIN_CYCLES.get(result.name)
        target486 = TARGET_486_CYCLES.get(result.name)
        current_text = fmt_cycles(current)
        if current is not None:
            # color against the 486 goal when defined, else the 386 target
            ref = target486 if target486 is not None else result.target_cycles
            current_text = colorize(current_text, classify_delta(current - ref), color_enabled)
        rows.append([
            result.description,
            fmt_cycles(result.target_cycles),
            fmt_cycles(target486),
            fmt_cycles(baseline),
            current_text,
        ])

    plain_rows = [
        [result.description, fmt_cycles(result.target_cycles),
         fmt_cycles(TARGET_486_CYCLES.get(result.name)),
         fmt_cycles(Z386_04_MIN_CYCLES.get(result.name)),
         fmt_cycles(min(result.samples) if result.samples else None)]
        for result in results
    ]
    widths = [
        max(len(headers[index]), *(len(row[index]) for row in plain_rows))
        for index in range(len(headers))
    ]

    print("Timing comparison (best-case cycles)")
    print(format_table_row(headers, widths))
    print("| " + " | ".join(["---"] + ["---:"] * (len(headers) - 1)) + " |")
    for row in rows:
        print(format_table_row(row, widths))
    print()


def use_color(mode: str) -> bool:
    if mode == "always":
        return True
    if mode == "never":
        return False
    return sys.stdout.isatty() and os.environ.get("TERM") not in (None, "", "dumb")


def classify_delta(delta: float | None) -> str:
    if delta is None:
        return "plain"
    if delta <= 0.0:
        return "good"
    if delta <= 1.0:
        return "warn"
    return "bad"


def colorize(text: str, level: str, enable: bool) -> str:
    if not enable or level == "plain":
        return text
    color = {
        "good": "\033[92m",
        "warn": "\033[93m",
        "bad": "\033[91m",
    }[level]
    return f"{color}{text}\033[0m"


def run_trace_generation(cycles_limit: int) -> Path:
    cmd = [
        sys.executable,
        "test_protected_mode.py",
        TEST_NAME,
        "--trace",
        "-c",
        str(cycles_limit),
    ]
    result = subprocess.run(
        cmd,
        cwd=TESTS_DIR,
        capture_output=True,
        text=True,
        timeout=180,
    )
    if result.returncode != 0:
        details = result.stdout.strip() or result.stderr.strip() or "unknown error"
        raise SystemExit(f"Trace generation failed: {details}")
    return DEFAULT_TRACE


def measure_steady_phase(phase: SteadyPhase, i_first_events: list[tuple[int, int]], cycle_period: float) -> list[float]:
    events = [(time, eip) for time, eip in i_first_events if eip in phase.eips]
    phase_index = {eip: idx for idx, eip in enumerate(phase.eips)}

    samples: list[float] = []
    for (time_a, eip_a), (time_b, eip_b) in zip(events, events[1:]):
        if phase_index[eip_b] == phase_index[eip_a] + 1:
            samples.append(cycles(time_b - time_a, cycle_period))

    # Measure the steady-state middle, not the edges.  386 microcode does not
    # overlap between instructions, so i_first->i_first is the true per-instruction
    # cost -- but the FIRST copy is unreliable (store-to-load forwarding from the
    # phase setup, or a cold-miss first touch) and the LAST borders the verify.
    # Drop one sample at each end so the reported cost is the warm steady state.
    if len(samples) >= 4:
        samples = samples[1:-1]
    return samples


def measure_branch_phase(
    phase: BranchPhase,
    i_first_events: list[tuple[int, int]],
    cycle_period: float,
    window_cycles: float,
) -> list[float]:
    branch_times = [time for time, eip in i_first_events if eip == phase.branch_eip]
    target_times = [time for time, eip in i_first_events if eip == phase.target_eip]
    max_gap = window_cycles * cycle_period

    samples: list[float] = []
    target_index = 0

    for branch_time in branch_times:
        while target_index < len(target_times) and target_times[target_index] <= branch_time:
            target_index += 1
        if target_index >= len(target_times):
            break

        target_time = target_times[target_index]
        if target_time - branch_time > max_gap:
            continue

        samples.append(cycles(target_time - branch_time, cycle_period))
        target_index += 1

    return samples


def main() -> int:
    parser = argparse.ArgumentParser(description="Measure instruction timing microbenchmark")
    parser.add_argument(
        "trace_file",
        nargs="?",
        default=str(DEFAULT_TRACE),
        help=f"Trace file to analyze (default: {DEFAULT_TRACE})",
    )
    parser.add_argument(
        "--run",
        action="store_true",
        help="Regenerate the instruction_timing trace before analysis",
    )
    parser.add_argument(
        "--cycles",
        type=int,
        default=20_000,
        help="Cycle limit when regenerating the trace (default: 20000)",
    )
    parser.add_argument(
        "--window-cycles",
        type=float,
        default=40.0,
        help="Maximum branch->target matching window in cycles (default: 40)",
    )
    parser.add_argument(
        "--color",
        choices=("auto", "always", "never"),
        default="auto",
        help="Colorize good/bad timing results (default: auto)",
    )
    args = parser.parse_args()

    trace_path = Path(args.trace_file)
    if args.run:
        trace_path = run_trace_generation(args.cycles)

    if not trace_path.exists():
        raise SystemExit(f"Trace file not found: {trace_path}")

    clk_rises, i_first_events = parse_trace(trace_path)
    cycle_period = infer_cycle_period(clk_rises)
    color_enabled = use_color(args.color)

    print(f"Trace: {trace_path}")
    print(f"Clock period: {cycle_period:.1f} ns")
    print()

    results: list[PhaseResult] = []

    for phase in STEADY_PHASES:
        samples = measure_steady_phase(phase, i_first_events, cycle_period)
        results.append(PhaseResult(phase.name, phase.description, phase.target_cycles, tuple(samples)))

    for phase in BRANCH_PHASES:
        samples = measure_branch_phase(phase, i_first_events, cycle_period, args.window_cycles)
        results.append(PhaseResult(phase.name, phase.description, phase.target_cycles, tuple(samples), branch=True))

    print_comparison_table(results, color_enabled)

    for result in results:
        samples = list(result.samples)
        avg = statistics.mean(samples) if samples else None
        delta = (avg - result.target_cycles) if avg is not None else None
        level = classify_delta(delta)
        delta_text = f"{delta:+.2f}" if result.branch and delta is not None else f"{delta:+.1f}" if delta is not None else "n/a"
        print(f"{result.name}: {result.description}")
        print(f"  target:  {result.target_cycles:.2f} cycles")
        print(f"  samples: {len(samples)}")
        measurement = "branch i_first -> target i_first" if result.branch else "i_first -> next i_first"
        print(
            f"  measured {measurement}: "
            f"{colorize(f'{summarize(samples)} cycles', level, color_enabled)}"
        )
        print(
            "  delta vs 386 target: "
            f"{colorize(f'{delta_text} cycles', level, color_enabled)}"
        )
        target486 = TARGET_486_CYCLES.get(result.name)
        if target486 is not None and avg is not None:
            d486 = avg - target486
            print(f"  delta vs 486 target: {d486:+.1f} cycles (486 = {target486:g})")
        print()

    return 0


if __name__ == "__main__":
    sys.exit(main())
